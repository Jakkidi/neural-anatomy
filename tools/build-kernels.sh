#!/usr/bin/env bash
# Rebuilds src/core/kernels.wasm.js from src/core/kernels.c.
# Needs clang with the wasm32 target and wasm-ld. The output is committed,
# so nobody has to run this to use the app.
set -euo pipefail
cd "$(dirname "$0")/.."
OUT=$(mktemp -d)
clang --target=wasm32 -O3 -msimd128 -ffast-math -nostdlib -fno-builtin \
  -Wl,--no-entry -Wl,--import-memory -Wl,--export=__heap_base \
  -Wl,--stack-first -Wl,-z,stack-size=65536 -Wl,--strip-all \
  -Wl,--max-memory=4294901760 \
  -o "$OUT/kernels.wasm" src/core/kernels.c
node -e '
const fs = require("fs");
const bytes = fs.readFileSync(process.argv[1]);
const text = `// Generated by tools/build-kernels.sh from kernels.c. Do not edit.\nexport const KERNELS_WASM_BASE64 =\n  "${bytes.toString("base64")}";\n`;
fs.writeFileSync("src/core/kernels.wasm.js", text);
console.log("kernels.wasm", bytes.length, "bytes");
' "$OUT/kernels.wasm"

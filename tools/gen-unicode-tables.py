#!/usr/bin/env python3
"""Writes desktop/engine/src/unicode_tables.rs.

GPT-2's tokenizer splits text with a pattern that uses \\p{L} (any letter) and
\\p{N} (any number). Rust's standard library has no such classes, so the engine
carries the two tables. This script builds them from Python's unicodedata.

    python3 tools/gen-unicode-tables.py            # rewrite the file
    python3 tools/gen-unicode-tables.py --check    # fail if the file is out of date
"""
import sys
import textwrap
import unicodedata
from pathlib import Path

TARGET = Path(__file__).resolve().parent.parent / "desktop" / "engine" / "src" / "unicode_tables.rs"


def ranges(initial):
    """Inclusive code point ranges whose general category starts with `initial`."""
    out, start = [], None
    for cp in range(0x110000):
        inside = unicodedata.category(chr(cp)).startswith(initial)
        if inside and start is None:
            start = cp
        elif not inside and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def table(name, pairs):
    body = ", ".join(f"(0x{lo:X}, 0x{hi:X})" for lo, hi in pairs) + ","
    # break only between pairs, never inside one
    lines = textwrap.wrap(body.replace(", 0x", ",\u00a00x"), width=116, break_long_words=False, break_on_hyphens=False)
    lines = [line.replace("\u00a0", " ") for line in lines]
    return f"pub static {name}: &[(u32, u32)] = &[\n" + "\n".join("    " + line for line in lines) + "\n];\n"


def render():
    return (
        f"// Generated by tools/gen-unicode-tables.py from Unicode {unicodedata.unidata_version}. Do not edit.\n"
        "// Code point ranges of the general categories L (letters) and N (numbers), which\n"
        "// GPT-2's tokenizer pattern uses as \\p{L} and \\p{N}.\n\n"
        + table("LETTER", ranges("L"))
        + "\n"
        + table("NUMBER", ranges("N"))
        + """
fn contains(table: &[(u32, u32)], c: char) -> bool {
    let cp = c as u32;
    table.binary_search_by(|&(lo, hi)| if cp < lo { std::cmp::Ordering::Greater } else if cp > hi { std::cmp::Ordering::Less } else { std::cmp::Ordering::Equal }).is_ok()
}

pub fn is_letter(c: char) -> bool {
    if c.is_ascii() { c.is_ascii_alphabetic() } else { contains(LETTER, c) }
}

pub fn is_number(c: char) -> bool {
    if c.is_ascii() { c.is_ascii_digit() } else { contains(NUMBER, c) }
}
"""
    )


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        if TARGET.read_text(encoding="utf-8") != text:
            sys.exit(f"{TARGET} is out of date. Run this script without --check.")
        print("unicode_tables.rs is up to date.")
    else:
        TARGET.write_text(text, encoding="utf-8")
        print(f"wrote {TARGET}")
